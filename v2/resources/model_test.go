// TestModel_Create_SRIOV is a regression test for CI-865.
//
// A model that declares an SR-IOV physical function (IO_TYPE_ETH_PF with vfs)
// makes zedcloud auto-create additional VF io_members (IO_TYPE_ETH_VF). Those
// members are not in the terraform config, so before the fix every subsequent
// plan reported spurious drift (it tried to delete the VF members and got the
// remaining members out of order).
//
// The test asserts:
//  1. the VF members are actually created by the backend, and
//  2. re-planning the unchanged config yields an empty plan (the second
//     PlanOnly step fails if any diff is produced).
func TestModel_Create_SRIOV(t *testing.T) {
	var got models.SysModel

	input := testhelper.MustGetTestInput(t, "model/create_sriov.tf")
	const modelResource = "zedcloud_model.test_tf_provider_sriov"

	resource.Test(t, resource.TestCase{
		PreCheck:     func() { testhelper.CheckEnv(t) },
		CheckDestroy: testHardwareModelDestroy,
		Providers:    testAccProviders,
		Steps: []resource.TestStep{
			{
				Config: input,
				Check: resource.ComposeTestCheckFunc(
					testHardwareModelExists(modelResource, &got),
					// The 4 configured members are eth0..eth3; eth3 is the PF with
					// vfs.count = 4, so the backend must add 4 VF members => 8 total.
					testHardwareModelHasAutoGeneratedVFs(&got, "eth3", 4),
				),
			},
			// Re-plan the identical config: before the CI-865 fix this produced a
			// non-empty plan. PlanOnly defaults to ExpectNonEmptyPlan=false, so a
			// spurious diff fails the test.
			{
				Config:   input,
				PlanOnly: true,
			},
		},
	})
}

// testHardwareModelExists fetches the model from the API and stores it.
func testHardwareModelExists(resourceName string, out *models.SysModel) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		rs, ok := s.RootModule().Resources[resourceName]
		if !ok {
			return fmt.Errorf("model not found in state: %s", resourceName)
		}
		if rs.Primary.ID == "" {
			return fmt.Errorf("model ID is not set")
		}

		client := testProvider.Meta().(*api_client.ZedcloudAPI)
		params := hardware_model.NewHardwareModelGetHardwareModelParams()
		params.ID = rs.Primary.ID
		resp, err := client.HardwareModel.HardwareModelGetHardwareModel(params, nil)
		if err != nil {
			return fmt.Errorf("could not fetch model (%s): %w", rs.Primary.ID, err)
		}
		payload := resp.GetPayload()
		if payload == nil {
			return errors.New("nil payload in model existence check")
		}
		*out = *payload
		return nil
	}
}

// testHardwareModelHasAutoGeneratedVFs verifies the backend created one VF
// io_member per requested virtual function of the given physical function.
func testHardwareModelHasAutoGeneratedVFs(m *models.SysModel, pfLabel string, wantVFs int) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		var pfFound bool
		vfCount := 0
		for _, member := range m.IoMemberList {
			if member == nil || member.Ztype == nil {
				continue
			}
			if member.Logicallabel != nil && *member.Logicallabel == pfLabel {
				pfFound = true
			}
			if *member.Ztype == models.IoTypeIOTYPEETHVF && member.Parentassigngrp != "" {
				vfCount++
			}
		}
		if !pfFound {
			return fmt.Errorf("physical function %q not found in model io_member_list", pfLabel)
		}
		if vfCount != wantVFs {
			return fmt.Errorf("expected %d auto-generated VF members, got %d", wantVFs, vfCount)
		}
		return nil
	}
}

// testHardwareModelDestroy verifies the model (and brand) were destroyed.
func testHardwareModelDestroy(s *terraform.State) error {
	client := testProvider.Meta().(*api_client.ZedcloudAPI)

	for _, rs := range s.RootModule().Resources {
		if rs.Type != "zedcloud_model" {
			continue
		}
		params := hardware_model.NewHardwareModelGetHardwareModelParams()
		params.ID = rs.Primary.ID
		resp, err := client.HardwareModel.HardwareModelGetHardwareModel(params, nil)
		if err != nil {
			// Any error (including 404) means the model is gone.
			continue
		}
		if payload := resp.GetPayload(); payload != nil && payload.ID == rs.Primary.ID {
			return fmt.Errorf("destroy failed, model (%s) still exists", payload.ID)
		}
	}
	return nil
}
