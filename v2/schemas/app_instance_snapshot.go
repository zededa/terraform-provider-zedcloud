package schemas

import (
	"github.com/hashicorp/terraform-plugin-sdk/v2/helper/schema"
	"github.com/hashicorp/terraform-plugin-sdk/v2/helper/validation"
)

// AppInstanceSnapshotSchema is the schema of zedcloud_app_instance_snapshot.
// See docs/design/ple-576-app-instance-immediate-snapshots.md §4.2.
func AppInstanceSnapshotSchema() map[string]*schema.Schema {
	return map[string]*schema.Schema{
		"app_instance_id": {
			Description:  "ID of the edge application instance to snapshot.",
			Type:         schema.TypeString,
			Required:     true,
			ForceNew:     true,
			ValidateFunc: validation.StringIsNotEmpty,
		},
		"triggers": {
			Description: "Arbitrary values. Changing any of them takes a new snapshot (and, because the controller " +
				"keeps one snapshot per app instance, drops the previous one).",
			Type:     schema.TypeMap,
			Elem:     &schema.Schema{Type: schema.TypeString},
			Optional: true,
			ForceNew: true,
		},
		"wait_for_ready": {
			Description: "Wait until the edge node reports the snapshot as `CREATED`. Defaults to `true`. " +
				"The snapshot is taken by the edge node, so an offline node makes the wait time out.",
			Type:     schema.TypeBool,
			Optional: true,
			Default:  true,
		},
		"skip_capability_check": {
			Description: "Skip the check that the edge node's API capability level is at least " +
				"`API_CAPABILITY_VOLUME_SNAPSHOTS_IMMEDIATE` (zcli's `-f`). Defaults to `false`.",
			Type:     schema.TypeBool,
			Optional: true,
			Default:  false,
		},
		"name": {
			Description: "Snapshot name, generated by the controller (`snapshot-<timestamp>-<suffix>`).",
			Type:        schema.TypeString,
			Computed:    true,
		},
		"state": {
			Description: "Snapshot state as last reported: `CREATING`, `CREATED`, `CREATE_FAILED`, `ROLLING_BACK`, " +
				"`ACTIVE`, `ROLLBACK_FAILED`, `DELETING`, `DELETE_FAILED`, `DELETED`, `IDLE` or `INVALID`.",
			Type:     schema.TypeString,
			Computed: true,
		},
		"config_json": {
			Description: "The app instance configuration captured by the snapshot, as JSON, without encrypted secrets.",
			Type:        schema.TypeString,
			Computed:    true,
			Sensitive:   true,
		},
	}
}

// AppInstanceSnapshotActivationSchema is the schema of
// zedcloud_app_instance_snapshot_activation. See the design doc §4.3.
func AppInstanceSnapshotActivationSchema() map[string]*schema.Schema {
	return map[string]*schema.Schema{
		"app_instance_id": {
			Description:  "ID of the edge application instance to roll back.",
			Type:         schema.TypeString,
			Required:     true,
			ForceNew:     true,
			ValidateFunc: validation.StringIsNotEmpty,
		},
		"snapshot_name": {
			Description: "Name of the snapshot to roll back to. Any snapshot of the app instance, whether or not " +
				"Terraform created it, that has not been rolled back to before.",
			Type:         schema.TypeString,
			Required:     true,
			ForceNew:     true,
			ValidateFunc: validation.StringIsNotEmpty,
		},
		"triggers": {
			Description: "Arbitrary values. Changing any of them replaces the resource and rolls back again. " +
				"The controller can roll back to a given snapshot only once, so point `snapshot_name` at a new " +
				"snapshot when you do.",
			Type:     schema.TypeMap,
			Elem:     &schema.Schema{Type: schema.TypeString},
			Optional: true,
			ForceNew: true,
		},
		"snapshot_id": {
			Description: "ID of the snapshot that was activated.",
			Type:        schema.TypeString,
			Computed:    true,
		},
		"state": {
			Description: "Snapshot state as last reported. `ACTIVE` after a successful rollback.",
			Type:        schema.TypeString,
			Computed:    true,
		},
		"activated_at": {
			Description: "When the controller recorded the snapshot as `ACTIVE`.",
			Type:        schema.TypeString,
			Computed:    true,
		},
	}
}

// AppInstanceSnapshotsDataSourceSchema is the schema of
// data.zedcloud_app_instance_snapshots. See the design doc §4.5.
func AppInstanceSnapshotsDataSourceSchema() map[string]*schema.Schema {
	return map[string]*schema.Schema{
		"app_instance_id": {
			Description:  "ID of the edge application instance.",
			Type:         schema.TypeString,
			Required:     true,
			ValidateFunc: validation.StringIsNotEmpty,
		},
		"name": {
			Description: "Only return the snapshot with this name.",
			Type:        schema.TypeString,
			Optional:    true,
		},
		"snapshots": {
			Description: "The app instance's snapshots. The controller keeps at most one per app instance in practice.",
			Type:        schema.TypeList,
			Computed:    true,
			Elem: &schema.Resource{
				Schema: map[string]*schema.Schema{
					"id":    {Type: schema.TypeString, Computed: true, Description: "Snapshot ID."},
					"name":  {Type: schema.TypeString, Computed: true, Description: "Snapshot name."},
					"state": {Type: schema.TypeString, Computed: true, Description: "Snapshot state."},
				},
			},
		},
	}
}
