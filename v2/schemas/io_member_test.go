package schemas

import (
	"testing"

	"github.com/zededa/terraform-provider-zedcloud/v2/models"
)

func strptr(s string) *string { return &s }
func i64ptr(i int64) *int64   { return &i }

// ioMember builds a minimally-populated io_member with all the fields that
// CompareIoMemberLists dereferences.
func ioMember(label, ztype, parentassigngrp string, vfsCount int64) *models.IoMember {
	m := &models.IoMember{
		Assigngrp:       strptr(label),
		Cost:            i64ptr(0),
		Logicallabel:    strptr(label),
		Parentassigngrp: parentassigngrp,
		Phyaddrs:        map[string]string{},
		Phylabel:        strptr(label),
		Usage:           models.NewAdapterUsage(models.AdapterUsage("ADAPTER_USAGE_MANAGEMENT")),
		Ztype:           models.NewIoType(models.IoType(ztype)),
	}
	if vfsCount > 0 {
		m.Vfs = &models.Vfs{Count: vfsCount}
	}
	return m
}

func TestFilterAutoGeneratedVFs(t *testing.T) {
	members := []*models.IoMember{
		ioMember("eth0", "IO_TYPE_ETH", "", 0),
		ioMember("eth3", "IO_TYPE_ETH_PF", "", 4),
		ioMember("eth3vf0", "IO_TYPE_ETH_VF", "vf0", 0),
		ioMember("eth3vf1", "IO_TYPE_ETH_VF", "vf1", 0),
	}

	got := filterAutoGeneratedVFs(members)
	if len(got) != 2 {
		t.Fatalf("expected 2 members after filtering VFs, got %d", len(got))
	}
	for _, m := range got {
		if *m.Ztype == models.IoTypeIOTYPEETHVF {
			t.Fatalf("VF member %q was not filtered out", *m.Logicallabel)
		}
	}
}

// suppress mirrors what diffSuppressIoMemberListOrder does with the values it
// reads from state (old) and config (new): filter the auto-generated VFs from
// both sides, then compare.
func suppress(state, config []*models.IoMember) bool {
	return CompareIoMemberLists(filterAutoGeneratedVFs(state), filterAutoGeneratedVFs(config))
}

func TestCompareIoMemberLists_SRIOV(t *testing.T) {
	// The config declares eth0..eth3 with eth3 a PF (vfs.count = 4).
	config := []*models.IoMember{
		ioMember("eth0", "IO_TYPE_ETH", "", 0),
		ioMember("eth1", "IO_TYPE_ETH", "", 0),
		ioMember("eth2", "IO_TYPE_ETH", "", 0),
		ioMember("eth3", "IO_TYPE_ETH_PF", "", 4),
	}

	// The backend returns the same members reordered (eth0 last) plus 4
	// auto-created VF members for the PF (CI-865).
	stateWithVFs := []*models.IoMember{
		ioMember("eth1", "IO_TYPE_ETH", "", 0),
		ioMember("eth2", "IO_TYPE_ETH", "", 0),
		ioMember("eth3", "IO_TYPE_ETH_PF", "", 4),
		ioMember("eth3vf0", "IO_TYPE_ETH_VF", "vf0", 0),
		ioMember("eth3vf1", "IO_TYPE_ETH_VF", "vf1", 0),
		ioMember("eth3vf2", "IO_TYPE_ETH_VF", "vf2", 0),
		ioMember("eth3vf3", "IO_TYPE_ETH_VF", "vf3", 0),
		ioMember("eth0", "IO_TYPE_ETH", "", 0),
	}

	tests := []struct {
		name         string
		state        []*models.IoMember
		config       []*models.IoMember
		wantSuppress bool
	}{
		{
			// The regression: extra VFs + reordering must NOT be reported as drift.
			name:         "auto-generated VFs and reordering are suppressed",
			state:        stateWithVFs,
			config:       config,
			wantSuppress: true,
		},
		{
			// A genuine change to the PF's vfs.count must still surface.
			name:  "vfs count change is not suppressed",
			state: stateWithVFs,
			config: []*models.IoMember{
				ioMember("eth0", "IO_TYPE_ETH", "", 0),
				ioMember("eth1", "IO_TYPE_ETH", "", 0),
				ioMember("eth2", "IO_TYPE_ETH", "", 0),
				ioMember("eth3", "IO_TYPE_ETH_PF", "", 2),
			},
			wantSuppress: false,
		},
		{
			// Removing a real (non-VF) member must still surface.
			name:  "removed member is not suppressed",
			state: stateWithVFs,
			config: []*models.IoMember{
				ioMember("eth0", "IO_TYPE_ETH", "", 0),
				ioMember("eth1", "IO_TYPE_ETH", "", 0),
				ioMember("eth3", "IO_TYPE_ETH_PF", "", 4),
			},
			wantSuppress: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := suppress(tt.state, tt.config); got != tt.wantSuppress {
				t.Fatalf("suppress() = %v, want %v", got, tt.wantSuppress)
			}
		})
	}
}
